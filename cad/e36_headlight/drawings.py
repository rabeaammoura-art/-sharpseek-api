def sheet3(pdf):
    fig = plt.figure(figsize=(16.54, 11.69)); frame(fig, "Sheet 3 — Separate printed parts (installed orientation, bounding dims)", 3)
    names = list(NEW)
    for k, n in enumerate(names):
        m = NEW[n]; ax = fig.add_axes([0.03 + (k % 4) * 0.245, 0.50 - (k // 4) * 0.44, 0.22, 0.38])
        e = m.extents
        # pick the view along the thinnest axis
        ax_i = int(np.argmin(e)); ij = [q for q in range(3) if q != ax_i]
        view = np.zeros(3); view[ax_i] = -1
        silhouette(ax, m, view, ij[0], ij[1], COL["new"], 0.5)
        b = m.bounds
        dim(ax, (b[0, ij[0]], b[1, ij[1]]), (b[1, ij[0]], b[1, ij[1]]), f"{e[ij[0]]:.1f}", off=4)
        dim(ax, (b[1, ij[0]], b[0, ij[1]]), (b[1, ij[0]], b[1, ij[1]]), f"{e[ij[1]]:.1f}", off=4, vertical=True)
        ax.set_title(f"{n}  ({e[0]:.1f} x {e[1]:.1f} x {e[2]:.1f}, {m.volume/1000:.1f} cm³)\nview along {'XYZ'[ax_i]}", fontsize=8)
        ax.set_aspect("equal"); ax.axis("off")
    pdf.savefig(fig); fig.savefig(DW / "sheet3_parts.png", dpi=110); plt.close(fig)


with PdfPages(DW / "E36_headlight_drawings.pdf") as pdf:
    sheet1(pdf); sheet2(pdf); sheet3(pdf)
