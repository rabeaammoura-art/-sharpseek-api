    frame(fig, "Sheet 1 — Assembly overview & key dimensions", 1)
    cx, cz = P.PROJ_C; dx, dz = P.DEVIL_C; f = G.projector_frame(); d = G.devil_frame()
    # front view: section just behind the face skin + aperture circles
    ax = fig.add_axes([0.04, 0.50, 0.55, 0.42]); ax.set_title("Front view (from -Y) — outline + section Y=-60", fontsize=9)
    silhouette(ax, H, np.array([0, -1, 0]), 0, 2, COL["housing"], 0.35)
    for x, z, lab in ((cx, cz, "Bi-LED (inboard)"), (dx, dz, "Devil Eye (outboard)")):
        ax.add_patch(plt.Circle((x, z), 46.5, fill=False, color=COL["new"], lw=1.2)); ax.plot(x, z, "+", color=COL["new"])
        ax.text(x, z - 58, lab, ha="center", fontsize=7, color=COL["new"])
    b = H.bounds
    dim(ax, (b[0, 0], b[1, 2]), (b[1, 0], b[1, 2]), f"{b[1,0]-b[0,0]:.1f} overall (unchanged)", off=8)
    dim(ax, (cx, cz), (dx, dz), f"{dx-cx:.1f} c/c", off=-75)
    dim(ax, (b[1, 0], b[0, 2]), (b[1, 0], b[1, 2]), f"{b[1,2]-b[0,2]:.1f} overall", off=10, vertical=True)
    ax.text(cx, cz + 50, "Ø93", ha="center", fontsize=7); ax.text(dx, dz + 50, "Ø93 (original)", ha="center", fontsize=7)
    ax.text(b[0, 0], 190, f"axes Z={cz:.1f}", fontsize=7)
    ax.text(150, 128, "turn-signal\nbracket (orig.)\n→ fender", fontsize=6, ha="right")
    ax.text(-170, 128, "← grille", fontsize=6)
    ax.set_aspect("equal"); ax.axis("off")
    # plan section Z = axis height
    ax = fig.add_axes([0.62, 0.50, 0.36, 0.42]); ax.set_title(f"Plan section Z={cz:.1f} (looking down)", fontsize=9)
    section(ax, H, [0, 0, cz], [0, 0, 1], 0, 1, COL["housing"], 0.8, fill=COL["housing"])
    for n, m in NEW.items(): section(ax, m, [0, 0, cz], [0, 0, 1], 0, 1, COL["new"], 0.8, fill=COL["new"])
    for n, m in PH.items(): section(ax, m, [0, 0, cz], [0, 0, 1], 0, 1, COL["ph"], 0.6)
    dim(ax, (cx - 40, f["y_front"]), (cx + 40, f["y_front"]), "Ø80* shroud", off=-30)
    ax.axhline(f["y_front"], color=COL["new"], lw=0.3, ls="--"); ax.text(-175, f["y_front"] - 3, f"lens front Y={f['y_front']:.1f}*", fontsize=6)
    ax.axhline(d["y_front"], color=COL["new"], lw=0.3, ls="--"); ax.text(60, d["y_front"] - 3, f"eye front Y={d['y_front']:.1f}*", fontsize=6)
    ax.set_aspect("equal"); ax.axis("off"); ax.invert_yaxis()
    # side section through projector axis
    ax = fig.add_axes([0.04, 0.06, 0.44, 0.40]); ax.set_title(f"Section X={cx:.1f} (projector axis), looking outboard", fontsize=9)
    section(ax, H, [cx, 0, 0], [1, 0, 0], 1, 2, COL["housing"], 0.8, fill=COL["housing"])
    for n, m in NEW.items(): section(ax, m, [cx, 0, 0], [1, 0, 0], 1, 2, COL["new"], 0.8, fill=COL["new"])
    section(ax, PH["PH_projector_ASSUMED"], [cx, 0, 0], [1, 0, 0], 1, 2, COL["ph"], 0.6)
    dim(ax, (-60, P.BOTTOM_PLATE_TOP), (-60, P.TOP_PLATE_UNDERSIDE_FRONT), f"{P.TOP_PLATE_UNDERSIDE_FRONT-P.BOTTOM_PLATE_TOP:.0f} clear height", off=95, vertical=True)
    dim(ax, (f["y_front"], cz), (f["y_mount"], cz), f"{P.PROJ_SHROUD_L:.0f}* shroud", off=-48)
    ax.text(f["y_mount"] + 2, cz + 47, f"mount face Y={f['y_mount']:.1f}", fontsize=6)
    ax.set_aspect("equal"); ax.axis("off")
    # side section through devil eye axis
    ax = fig.add_axes([0.52, 0.06, 0.44, 0.40]); ax.set_title(f"Section X={dx:.1f} (Devil Eye axis), looking outboard", fontsize=9)
    section(ax, H, [dx, 0, 0], [1, 0, 0], 1, 2, COL["housing"], 0.8, fill=COL["housing"])
    for n, m in NEW.items(): section(ax, m, [dx, 0, 0], [1, 0, 0], 1, 2, COL["new"], 0.8, fill=COL["new"])
    section(ax, PH["PH_devil_eye_ASSUMED"], [dx, 0, 0], [1, 0, 0], 1, 2, COL["ph"], 0.6)
    ax.axvline(P.LIGHTRING_SEAT_Y, color="k", lw=0.3, ls=":"); ax.text(P.LIGHTRING_SEAT_Y + 1, 255, f"ring seat Y={P.LIGHTRING_SEAT_Y} (orig.)", fontsize=6)
    ax.set_aspect("equal"); ax.axis("off")
    pdf.savefig(fig); fig.savefig(DW / "sheet1_assembly.png", dpi=110); plt.close(fig)


