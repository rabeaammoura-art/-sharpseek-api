def section(ax, mesh, origin, normal, i, j, color, lw=0.8, fill=None):
    s = mesh.section(plane_origin=origin, plane_normal=normal)
    if s is None: return
    for e in s.discrete:
        ax.plot(e[:, i], e[:, j], color=color, lw=lw)
        if fill: ax.fill(e[:, i], e[:, j], color=fill, alpha=0.18, lw=0)


def silhouette(ax, mesh, view, i, j, color, lw=0.5):
    """Outline edges (feature edges facing the viewer)."""
    edges = mesh.edges_unique[mesh.face_adjacency_edges] if len(mesh.face_adjacency) else []
    ang = mesh.face_adjacency_angles
    sel = ang > np.radians(25)
    n = mesh.face_normals[mesh.face_adjacency]; vis = (n @ view).max(1) > 0
    for a, b in mesh.vertices[mesh.face_adjacency_edges[sel & vis]][:, :, [i, j]].transpose(0, 1, 2):
        ax.plot([a[0], b[0]], [a[1], b[1]], color=color, lw=lw)


def dim(ax, p0, p1, text, off=8, vertical=False, fs=7):
    (x0, y0), (x1, y1) = p0, p1
    if vertical:
        x = max(x0, x1) + off
        ax.annotate("", (x, y0), (x, y1), arrowprops=dict(arrowstyle="<->", lw=0.6))
        ax.plot([x0, x], [y0, y0], lw=0.3, color="k"); ax.plot([x1, x], [y1, y1], lw=0.3, color="k")
        ax.text(x + 1.5, (y0 + y1) / 2, text, fontsize=fs, rotation=90, va="center")
    else:
        y = max(y0, y1) + off
        ax.annotate("", (x0, y), (x1, y), arrowprops=dict(arrowstyle="<->", lw=0.6))
        ax.plot([x0, x0], [y0, y], lw=0.3, color="k"); ax.plot([x1, x1], [y1, y], lw=0.3, color="k")
        ax.text((x0 + x1) / 2, y + 1.5, text, fontsize=fs, ha="center")


def frame(fig, title, sheet):
    fig.text(0.01, 0.985, title, fontsize=12, weight="bold", va="top")
    fig.text(0.01, 0.958, "BMW E36 modular headlight — LEFT (Vänster) shown, RIGHT = mirror.  Units mm.  Frame: original housing STL "
             "(-Y forward, +Z up, +X outboard).  Black = housing (modified original), blue = new printed parts, "
             "grey = ASSUMED module envelopes, red = purchased hardware.", fontsize=7, va="top")
    fig.text(0.99, 0.01, f"Sheet {sheet}  |  generated by cad/e36_headlight/drawings.py from out/*.stl  |  dims marked * depend on ASSUMED module data",
             fontsize=6.5, ha="right")


